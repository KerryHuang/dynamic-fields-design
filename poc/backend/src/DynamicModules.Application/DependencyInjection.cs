using DynamicModules.Application.Common.Behaviors;
using DynamicModules.Application.Common.Security;
using DynamicModules.Domain.FieldTypes;
using FluentValidation;
using Microsoft.Extensions.DependencyInjection;

namespace DynamicModules.Application;

public static class DependencyInjection
{
    public static IServiceCollection AddApplication(this IServiceCollection services)
    {
        var assembly = typeof(DependencyInjection).Assembly;
        services.AddMediatR(cfg =>
        {
            cfg.RegisterServicesFromAssembly(assembly);
            cfg.AddOpenBehavior(typeof(DesignerAccessBehavior<,>));
            cfg.AddOpenBehavior(typeof(SystemAdminBehavior<,>));
            cfg.AddOpenBehavior(typeof(MasterDesignerBehavior<,>));
            cfg.AddOpenBehavior(typeof(ValidationBehavior<,>));
            cfg.AddOpenBehavior(typeof(TransactionBehavior<,>));
            // 在交易之內：寫入鎖已持有，冪等查詢與寫入、事件與驗證才在同一把鎖之下（設計 §2）
            cfg.AddOpenBehavior(typeof(IdempotencyBehavior<,>));
            cfg.AddOpenBehavior(typeof(RecordEffectsBehavior<,>));
        });
        services.AddValidatorsFromAssembly(assembly);
        services.AddSingleton<Common.Security.LoginThrottle>();
        services.AddScoped<Common.IWriteJournal, Common.WriteJournal>();
        services.AddScoped<Common.AfterCommitActions>();
        services.AddScoped<Common.IOperationContext, Common.OperationContext>();
        services.AddScoped<ISystemIdentity, SystemIdentity>();
        services.AddScoped<FieldLocks>();
        services.AddScoped<IDynamicAccessGuard, DynamicAccessGuard>();
        services.AddScoped<Dynamic.SchemaService.Queries.GetModuleSchema.ModuleSchemaBuilder>();
        services.AddScoped<Dynamic.References.ReferenceValidator>();
        services.AddScoped<Dynamic.References.ReferenceResolver>();
        services.AddScoped<Dynamic.References.ReferenceFill>();
        services.AddScoped<Dynamic.WorkflowService.WorkflowEnforcer>();
        services.AddScoped<Dynamic.ConversionService.ConversionLedger>();
        services.AddScoped<Dynamic.ConversionService.ConversionValidator>();
        services.AddScoped<Dynamic.EventService.EventValidator>();
        services.AddScoped<Dynamic.EventService.EventHiddenGuard>();
        services.AddScoped<Dynamic.CheckService.CheckValidator>();
        services.AddScoped<Dynamic.LedgerService.LedgerValidator>();
        services.AddScoped<Dynamic.EventService.EventFactLock>();
        services.AddScoped<Dynamic.EventService.EffectBudget>();
        services.AddScoped<Dynamic.EventService.EffectWriter>();
        services.AddScoped<Dynamic.EventService.EffectApplier>();
        services.AddScoped<Dynamic.EventService.EventStage>();
        services.AddScoped<Dynamic.EventService.FactBackstopStage>();
        services.AddScoped<Common.Behaviors.IWriteStage>(sp => sp.GetRequiredService<Dynamic.EventService.FactBackstopStage>());
        services.AddScoped<Common.Behaviors.IWriteStage>(sp => sp.GetRequiredService<Dynamic.EventService.EventStage>());
        services.AddScoped<Dynamic.AppService.Integrations.IntegrationGuardStage>();
        services.AddScoped<Common.Behaviors.IWriteStage>(sp => sp.GetRequiredService<Dynamic.AppService.Integrations.IntegrationGuardStage>());
        services.AddScoped<Dynamic.CheckService.CheckEvaluator>();
        services.AddScoped<Dynamic.CheckService.CheckIndexer>();
        services.AddScoped<Dynamic.RecordService.IndexBackfillJob>();
        services.AddScoped<Dynamic.CheckService.CheckFieldGuard>();
        services.AddScoped<Dynamic.CheckService.CheckStage>();
        services.AddScoped<Common.Behaviors.IWriteStage>(sp => sp.GetRequiredService<Dynamic.CheckService.CheckStage>());
        services.AddScoped<Dynamic.LedgerService.LedgerGate>();
        services.AddScoped<Dynamic.LedgerService.ImmutableDataGuard>();
        services.AddScoped<Dynamic.ModuleService.TitleRewriteGuard>();
        services.AddScoped<Dynamic.LedgerService.LedgerReverser>();
        services.AddScoped<Dynamic.LedgerService.LedgerBackstopStage>();
        services.AddScoped<Common.Behaviors.IWriteStage>(sp => sp.GetRequiredService<Dynamic.LedgerService.LedgerBackstopStage>());
        services.AddSingleton<Dynamic.EventService.IEffectHandlerRegistry, Dynamic.EventService.EffectHandlerRegistry>();
        services.AddScoped<Dynamic.PrintService.PrintTemplateValidator>();
        services.AddScoped<Dynamic.References.ReferenceDeletePlanner>();
        services.AddScoped<Dynamic.RecordService.DetailWriter>();
        services.AddScoped<Dynamic.RecordService.DetailReader>();
        services.AddScoped<Dynamic.RecordService.RecordHistoryWriter>();
        services.AddScoped<Dynamic.Rollups.RollupRecalc>();
        services.AddScoped<Dynamic.RecordService.RecordCreator>();
        services.AddScoped<Dynamic.ImportService.ImportPlanner>();
        services.AddSingleton(FieldTypeRegistry.CreateDefault());
        services.AddSingleton<Dynamic.ExportService.ExportOptions>();
        services.AddSingleton<Dynamic.ReportService.ReportOptions>();
        services.AddScoped<Dynamic.ReportService.ReportRunner>();
        services.AddScoped<Dynamic.ReportService.ReportModuleLoader>();
        services.AddScoped<Dynamic.ReportService.ReportAccess>();
        services.AddScoped<Dynamic.DashboardService.DashboardAccess>();
        services.AddScoped<Dynamic.DashboardService.DashboardCardRunner>();
        services.AddScoped<Dynamic.ReportService.ReportDefinitionValidator>();
        services.AddSingleton(_ => Dynamic.TemplateService.TemplateCatalog.Load(Dynamic.TemplateService.TemplateCatalog.DefaultDirectory));
        services.AddScoped<Dynamic.TemplateService.ITemplateSource, Dynamic.TemplateService.TemplateSource>();
        services.AddScoped<Dynamic.TemplateService.TemplateInstantiator>();
        services.AddScoped<Dynamic.TemplateService.TemplateExporter>();
        services.AddSingleton(_ => Dynamic.AppService.AppCatalog.Load(Dynamic.AppService.AppCatalog.DefaultDirectory));
        services.AddScoped<Dynamic.AppService.AppPackageSource>();
        services.AddScoped<Dynamic.AppService.AppDependencyChecker>();
        services.AddScoped<Dynamic.AppService.AppOpenPlanner>();
        services.AddScoped<Dynamic.AppService.AppResponseBuilder>();
        services.AddScoped<Dynamic.AppService.AppFlowInstaller>();
        services.AddScoped<Dynamic.AppService.Commands.AppOpener>();
        services.AddScoped<Dynamic.AppService.SharedMasters.MasterSymbols>();
        services.AddScoped<Dynamic.AppService.SharedMasters.MasterGrants>();
        services.AddScoped<Dynamic.AppService.SharedMasters.MasterLifecycle>();
        services.AddScoped<Dynamic.AppService.SharedMasters.ContributionOrphans>();
        services.AddScoped<Dynamic.AppService.SharedMasters.MasterDesigner>();
        services.AddScoped<Dynamic.AppService.SharedMasters.MasterMerger>();
        services.AddScoped<Dynamic.AppService.Integrations.IntegrationReconciler>();
        services.AddScoped<Dynamic.AttachmentService.AttachmentUploadGate>();
        services.AddScoped<Dynamic.AppService.AppExporter>();
        services.AddScoped<Dynamic.DemoService.DemoPreflight>();
        services.AddScoped<Dynamic.DemoService.DemoStructure>();
        services.AddScoped<Dynamic.DeleteService.DeletePlanner>();
        services.AddScoped<Dynamic.DeleteService.ModuleRemover>();
        services.AddScoped<Dynamic.TaskService.TaskAccess>();
        services.AddScoped<Dynamic.TaskService.TaskSupport>();
        services.AddScoped<Dynamic.TaskService.TaskWriter>();
        services.AddScoped<Dynamic.TaskService.ITaskNotifier, Dynamic.NotificationService.TaskNotificationWriter>();
        services.AddScoped<Dynamic.NotificationService.INotificationReminderSource, Dynamic.NotificationService.TaskReminderSource>();
        services.AddScoped<Dynamic.OrganizationService.OrgSnapshotLoader>();
        services.AddScoped<Dynamic.OrganizationService.DepartmentValidator>();
        services.AddScoped<Dynamic.ApprovalService.ApprovalDefinitionValidator>();
        services.AddScoped<Dynamic.TaskService.TaskRecordStage>();
        services.AddScoped<Common.Behaviors.IWriteStage>(sp => sp.GetRequiredService<Dynamic.TaskService.TaskRecordStage>());
        return services;
    }
}
